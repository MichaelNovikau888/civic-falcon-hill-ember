const NEUTRAL_ZONES = new Set(["UTC", "Etc/UTC", "Etc/GMT", "GMT", "GB"]);

export function countryToCurrency(country: string): string | null {
  const code = country.trim().toUpperCase();
  if (!/^[A-Z]{2}$/.test(code)) return null;
  return COUNTRY_CURRENCY[code] ?? null;
}

export function timezoneToCurrency(timeZone: string): string | null {
  const zone = timeZone.trim();
  if (!TIME_ZONE_RE.test(zone) || NEUTRAL_ZONES.has(zone)) return null;
  return TIME_ZONE_CURRENCY[zone] ?? null;
}
